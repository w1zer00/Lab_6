import math

print("Завдання 1: Табуляція функції за допомогою циклу FOR")

# Введення даних з клавіатури
a = float(input("Введіть початок діапазону (a): "))
b = float(input("Введіть кінець діапазону (b): "))
h = float(input("Введіть крок (h): "))

print("\nРезультати табуляції:")
print(f"{'x':<10} | {'f(x)':<10}")
print("-" * 25)

# Розрахунок кількості кроків для циклу for
n = int((b - a) / h) + 1

for i in range(n):
    x = a + i * h
    # Перевірка ОДЗ (підкореневий вираз має бути >= 0)
    if x >= 0:
        argument = abs(x + math.sqrt(x))
        # Перевірка ОДЗ логарифма (аргумент має бути > 0)
        if argument > 0:
            y = math.log10(argument)
            print(f"{x:<10.2f} | {y:<10.4f}")
        else:
            print(f"{x:<10.2f} | Помилка (lg(0))")
    else:
        print(f"{x:<10.2f} | Помилка (x < 0)")

